const has = (k: string) => Object.prototype.hasOwnProperty.call(ES, k);

/** Returns a function that translates fixed PDF texts; English (and anything unknown) passes through unchanged. */
export function translator(lang: PdfLanguage): (s: string) => string {
  if (lang !== "es") return (s) => s;
  return (s) => {
    const k = (s || "").trim();
    return k && has(k) ? ES[k] : s;
  };
}

